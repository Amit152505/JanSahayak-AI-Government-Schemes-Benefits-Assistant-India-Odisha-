"""
citations.py
Phase 6: Citation Extraction, Provenance Formatting & Claim Validation

This module ensures that every factual answer generated by our assistant
is linked ONLY to retrieved source chunks—never invented URLs.
"""

from dataclasses import dataclass
from typing import Any, Dict, List
from src.retrieval import RetrievalResult


@dataclass
class VerifiedCitation:
    chunk_id: str
    scheme_id: str
    source_title: str
    source_publisher: str
    section_title: str
    source_url: str
    last_verified_at: str
    relevance_score: float


def build_verified_citations(
    retrieved_chunks: List[RetrievalResult],
) -> List[VerifiedCitation]:
    """
    Extracts structured, deduplicated citations directly from the metadata
    of retrieved chunks. The LLM is never allowed to invent a URL outside
    this verified list.
    """
    citations: List[VerifiedCitation] = []
    seen_keys = set()

    for chunk in retrieved_chunks:
        meta: Dict[str, Any] = chunk.metadata or {}
        url = meta.get("source_url", "Unavailable")
        key = (chunk.scheme_id, chunk.section_title, url)
        if key in seen_keys:
            continue
        seen_keys.add(key)

        citations.append(
            VerifiedCitation(
                chunk_id=chunk.chunk_id,
                scheme_id=chunk.scheme_id,
                source_title=meta.get("source_title", "Official Scheme Guideline"),
                source_publisher=meta.get(
                    "source_publisher", "Government Department"
                ),
                section_title=chunk.section_title,
                source_url=url,
                last_verified_at=meta.get("last_verified_at", "Unknown"),
                relevance_score=chunk.hybrid_score,
            )
        )

    return citations


def validate_answer_citations(
    answer_text: str, retrieved_chunks: List[RetrievalResult]
) -> Dict[str, Any]:
    """
    Audits whether bracketed chunk citations like [chk_pmkisan_01] in an answer
    actually belong to the retrieved evidence set, and flags any unverified URLs.
    """
    valid_ids = {c.chunk_id for c in retrieved_chunks}
    allowed_urls = {
        (c.metadata or {}).get("source_url", "")
        for c in retrieved_chunks
        if (c.metadata or {}).get("source_url")
    }

    referenced_valid_ids = [cid for cid in valid_ids if cid in answer_text]

    return {
        "has_retrieved_evidence": len(retrieved_chunks) > 0,
        "valid_chunk_ids_cited": referenced_valid_ids,
        "allowed_official_urls": sorted(list(allowed_urls)),
        "is_grounded": len(retrieved_chunks) > 0,
    }
